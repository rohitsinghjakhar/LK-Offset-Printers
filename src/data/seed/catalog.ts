import type { Category, DesignServiceItem, OptionChoice, OptionGroup, PriceMode, Product, Spec } from "@/types/catalog";
import type { L } from "@/types/i18n";

const l = (en: string, hi: string): L => ({ en, hi });
const mult = (value: number): PriceMode => ({ mode: "multiplier", value });
const per1000 = (value: number): PriceMode => ({ mode: "per1000", value });
const perUnit = (value: number): PriceMode => ({ mode: "perUnit", value });
const flat = (value: number): PriceMode => ({ mode: "flat", value });
const c = (id: string, en: string, hi: string, price?: PriceMode, hint?: L): OptionChoice => ({ id, label: l(en, hi), price, hint });
const single = (id: string, label: L, choices: OptionChoice[], def?: string): OptionGroup => ({
  id,
  label,
  kind: "single",
  choices,
  defaults: [def ?? choices[0].id],
});
const multi = (id: string, label: L, choices: OptionChoice[], defaults: string[] = []): OptionGroup => ({
  id,
  label,
  kind: "multi",
  choices,
  defaults,
});
const spec = (en: string, hi: string, valueEn: string, valueHi: string): Spec => ({ label: l(en, hi), value: l(valueEn, valueHi) });

